// Release signing is read from an owner-controlled, git-ignored keystore.properties file.
// If it is absent the release build is produced unsigned (it can still be signed later with apksigner).
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

